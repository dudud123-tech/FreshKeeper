import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const WORKER_DIR = path.resolve(SCRIPT_DIR, "..");
const REPOSITORY_ROOT = path.resolve(WORKER_DIR, "..", "..");
const SOURCE_PATH = path.join(REPOSITORY_ROOT, "mobile", "src", "data", "productClassifier.json");
const FOOD_RULES_PATH = path.join(REPOSITORY_ROOT, "mobile", "src", "data", "foodRules.json");
const OUTPUT_DIR = path.join(WORKER_DIR, ".generated");
const OUTPUT_PATH = path.join(OUTPUT_DIR, "product-classifications-seed.sql");

if (!fs.existsSync(SOURCE_PATH)) {
  throw new Error(`분류기 파일을 찾을 수 없습니다: ${SOURCE_PATH}`);
}

const classifier = JSON.parse(fs.readFileSync(SOURCE_PATH, "utf8"));
const foodRules = JSON.parse(fs.readFileSync(FOOD_RULES_PATH, "utf8"));
const rules = Array.isArray(classifier.productRules) ? classifier.productRules : [];
const catalog = new Map();

for (const rule of rules) {
  const normalizedName = normalizeProductName(rule?.n || rule?.name);
  const displayName = safeText(rule?.name, 140);
  const category = safeText(rule?.category, 40);
  const storage = safeText(rule?.storage, 20);
  const expiryDays = normalizeExpiryDays(rule?.days);
  if (!normalizedName || !displayName || !category || !storage || expiryDays === null) continue;
  if (catalog.has(normalizedName)) continue;
  catalog.set(normalizedName, {
    normalizedName,
    displayName,
    category,
    storage,
    expiryDays
  });
}

const generatedAt = new Date().toISOString();
const keywordRules = buildKeywordRules(foodRules);
const lines = [
  "-- Generated by tools/build-product-classification-seed.js",
  "-- Apply migration 0007_product_classifications.sql before importing this file.",
  "DELETE FROM product_classification_catalog;",
  "DELETE FROM product_classification_keyword_rules;"
];

for (const item of catalog.values()) {
  lines.push(
    `INSERT INTO product_classification_catalog ` +
    `(normalized_name, display_name, category, storage, expiry_days, source, updated_at) VALUES (` +
    `${sql(item.normalizedName)}, ${sql(item.displayName)}, ${sql(item.category)}, ${sql(item.storage)}, ` +
    `${item.expiryDays}, 'food-safety-catalog', ${sql(generatedAt)});`
  );
}

for (const item of keywordRules.values()) {
  lines.push(
    `INSERT INTO product_classification_keyword_rules ` +
    `(normalized_keyword, display_keyword, category, storage, expiry_days, priority, updated_at) VALUES (` +
    `${sql(item.normalizedKeyword)}, ${sql(item.displayKeyword)}, ${sql(item.category)}, ${sql(item.storage)}, ` +
    `${item.expiryDays}, ${item.priority}, ${sql(generatedAt)});`
  );
}

fs.mkdirSync(OUTPUT_DIR, { recursive: true });
fs.writeFileSync(OUTPUT_PATH, `${lines.join("\n")}\n`, "utf8");

console.log(`created: ${OUTPUT_PATH}`);
console.log(`catalog rows: ${catalog.size}`);
console.log(`keyword rules: ${keywordRules.size}`);

function buildKeywordRules(rules) {
  const results = new Map();
  const priorityEntries = Object.entries(rules.priorityCategoryKeywords || {});
  const categoryEntries = Object.entries(rules.categoryKeywords || {});

  const addEntries = (entries, priorityBase) => entries.forEach(([category, words], categoryIndex) => {
    for (const word of words || []) {
      const normalizedKeyword = normalizeProductName(word);
      if (normalizedKeyword.length < 2 || results.has(normalizedKeyword)) continue;
      results.set(normalizedKeyword, {
        normalizedKeyword,
        displayKeyword: safeText(word, 80),
        category,
        storage: storageForKeyword(word, category, rules),
        expiryDays: expiryDaysForKeyword(word, category, rules),
        priority: priorityBase - categoryIndex
      });
    }
  });

  addEntries(priorityEntries, 1000);
  addEntries(categoryEntries, 100);
  return results;
}

function storageForKeyword(word, category, rules) {
  const normalizedKeyword = normalizeProductName(word);
  if (
    category === "냉동식품" ||
    (rules.frozenStorageWords || []).some((value) => normalizedKeyword.includes(normalizeProductName(value)))
  ) {
    return "냉동";
  }
  if (
    (rules.roomStorageCategories || []).includes(category) ||
    (rules.roomStorageWords || []).some((value) => normalizedKeyword.includes(normalizeProductName(value)))
  ) {
    return "실온";
  }
  return "냉장";
}

function expiryDaysForKeyword(word, category, rules) {
  const normalizedKeyword = normalizeProductName(word);
  const expiryRule = (rules.keywordExpiryDays || []).find((entry) =>
    (entry.words || []).some((value) => normalizeProductName(value) === normalizedKeyword)
  );
  return normalizeExpiryDays(expiryRule?.days) ??
    normalizeExpiryDays(rules.categoryExpiryDays?.[category]) ??
    7;
}

function normalizeProductName(value) {
  return safeText(value, 140)
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]/gu, "");
}

function normalizeExpiryDays(value) {
  const number = Number(value);
  if (!Number.isFinite(number)) return null;
  return Math.max(0, Math.min(3650, Math.round(number)));
}

function safeText(value, maxLength) {
  return String(value || "").trim().slice(0, maxLength);
}

function sql(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}
